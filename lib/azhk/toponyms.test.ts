import { describe, expect, it } from "vitest";

import { extractToponyms } from "@/lib/azhk/toponyms";

const labels = (place: string) => extractToponyms(place).map((t) => t.label);

// Inputs are real (redacted) place texts from AZhK schedules.
describe("extractToponyms", () => {
  it.each([
    [
      "жилые дома (частный сектор) м-н Айгерим-1, ул. МТФ ;ул.Азаттык; м-н Шанырак-2 ул.Веселова; Жанкожа батыра; Култегин",
      [
        "мкр. Айгерим-1",
        "ул. МТФ",
        "ул. Азаттык",
        "мкр. Шанырак-2",
        "ул. Веселова",
        "ул. Жанкожа батыра",
        "ул. Култегин",
      ],
    ],
    ["многоэтажные ж/дома: ул. Северное кольцо №№ 86/7, 86/8, 86/9", ["ул. Северное кольцо"]],
    [
      "ул. Верди, пр. Рыскулова, ул. Венецианова, Ниязбекова, Бродского.",
      ["ул. Верди", "пр. Рыскулова", "ул. Венецианова", "ул. Ниязбекова", "ул. Бродского"],
    ],
    [
      "Шакарима, Тургут Озала, Кулымбетова, Туркебаева",
      ["ул. Шакарима", "ул. Тургут Озала", "ул. Кулымбетова", "ул. Туркебаева"],
    ],
    [
      "м-он Акжар, ул.Амина Омирзакова, Сұлтан Байсұлтанов, Ш.Айманова",
      ["мкр. Акжар", "ул. Амина Омирзакова", "ул. Сұлтан Байсұлтанов", "ул. Ш.Айманова"],
    ],
    ["мкр.Айнабулак-2 д.32А,д.32б,д.32/2", ["мкр. Айнабулак-2"]],
    [
      "ул.Толстого, 6, ул.Шолохова, 13,13А, 13/1, 15, ул.Р.Зорге 5, 7, 11",
      ["ул. Толстого", "ул. Шолохова", "ул. Р.Зорге"],
    ],
    ["ул.Гете Иоганна д.40б-д.424, ул.Магнитная д.1-д.21", ["ул. Гете Иоганна", "ул. Магнитная"]],
    [
      "пер.Кошек батыра,д.мкр Трудовик, мкр.Томирис ул.Колсай д.10, д.16",
      ["пер. Кошек батыра", "мкр. Трудовик", "мкр. Томирис", "ул. Колсай"],
    ],
    ["мкр. Мирас 128", ["мкр. Мирас"]],
    ["мкр.8, д.29-34", ["мкр. 8"]],
    [
      "ул.1-я Кирпично-Заводская д.7/Фурманова/Аль-Фараби",
      ["ул. 1-я Кирпично-Заводская", "ул. Фурманова", "ул. Аль-Фараби"],
    ],
    ["мкр Горный Гигант", ["мкр. Горный Гигант"]],
    ['м-он "Самал-1", д.19 ТОО "Инж.ком. сети САМАЛ"', ["мкр. Самал-1"]],
  ])("%j", (place, expected) => {
    expect(labels(place)).toEqual(expected);
  });

  it("skips organisations, redaction placeholders and house numbers", () => {
    expect(labels('пр.Достык, д.240 ТОО "Компания Достар"')).toEqual(["пр. Достык"]);
    expect(labels("Акимат Ауэзовский, ЖК Алтын Сарай")).toEqual(["ЖК Алтын Сарай"]);
    expect(
      labels(
        "[ИП] - г.Алматы, м-он Айгерим-2, ул.Кожаханова,18; [ИП], [частное лицо] (ул.Пушкина, д.3/1)",
      ),
    ).toEqual(["мкр. Айгерим-2", "ул. Кожаханова", "ул. Пушкина"]);
  });

  it("does not mistake words that merely start like a type for one", () => {
    expect(labels("Прокофьева, Улжан")).toEqual(["ул. Прокофьева", "ул. Улжан"]);
    expect(labels("ЖКХ Медеуского района")).toEqual([]);
  });

  it("deduplicates by key and builds keys with the search normalizer", () => {
    const toponyms = extractToponyms("м-н Айгерим-1; мкр. Айгерим-1, ул.Ақжар");
    expect(toponyms.map((t) => t.key)).toEqual(["мкр айгерим 1", "ул акжар"]);
  });
});
