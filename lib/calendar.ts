/**
 * iCalendar (.ics, RFC 5545) export, built entirely in the browser: one file
 * with one or more outages that Apple Calendar, Google Calendar and Outlook import.
 */

/**
 * Almaty has been on UTC+5 all year round since 1 March 2024 (no DST), so times
 * are written in UTC: every calendar app reads them the same, no VTIMEZONE needed.
 */
const ALMATY_UTC_OFFSET_HOURS = 5;

/** How long before the outage the reminder fires: the evening before a morning cut. */
const REMINDER_BEFORE = "-PT12H";

const MAX_LINE_OCTETS = 75;

export interface CalendarEvent {
  /** Stable across downloads, so importing the same outage again updates it instead of duplicating. */
  uid: string;
  /** `YYYY-MM-DD`, Almaty. */
  date: string;
  /** `HH:mm`, Almaty. */
  timeFrom: string;
  timeTo: string;
  summary: string;
  location: string;
  description: string;
  url: string;
  reminder: string;
}

/** "2026-10-07" + "09:00" in Almaty → "20261007T040000Z". */
export function toUtcStamp(date: string, time: string): string {
  const [year = 0, month = 1, day = 1] = date.split("-").map(Number);
  const [hours = 0, minutes = 0] = time.split(":").map(Number);
  return formatUtc(
    new Date(Date.UTC(year, month - 1, day, hours - ALMATY_UTC_OFFSET_HOURS, minutes)),
  );
}

function formatUtc(moment: Date): string {
  return moment
    .toISOString()
    .replace(/[-:]/g, "")
    .replace(/\.\d{3}/, "");
}

/**
 * URI values can't be escaped like text, so they are normalised instead: `new URL`
 * drops line breaks, which would otherwise start a new property in the file.
 * Only http(s) links are kept.
 */
export function safeUri(value: string): string {
  const url = new URL(value);
  if (url.protocol !== "https:" && url.protocol !== "http:")
    throw new Error(`Not a web link: ${value}`);
  return url.href;
}

/** UIDs are generated by us; anything outside a safe set is dropped just in case. */
function safeUid(value: string): string {
  return value.replace(/[^\w@.-]/g, "");
}

/** TEXT values: backslash, semicolon, comma and line breaks must be escaped. */
export function escapeText(value: string): string {
  return value
    .replace(/\\/g, "\\\\")
    .replace(/;/g, "\\;")
    .replace(/,/g, "\\,")
    .replace(/\r?\n/g, "\\n");
}

/**
 * Lines longer than 75 octets are folded: CRLF plus a space. Counted in UTF-8
 * bytes (Cyrillic letters are two), never splitting a character.
 */
export function foldLine(line: string): string {
  const encoder = new TextEncoder();
  const parts: string[] = [];
  let current = "";
  let currentOctets = 0;
  for (const char of line) {
    const octets = encoder.encode(char).length;
    // Continuation lines start with a space, which counts towards their 75.
    const limit = parts.length === 0 ? MAX_LINE_OCTETS : MAX_LINE_OCTETS - 1;
    if (currentOctets + octets > limit) {
      parts.push(current);
      current = "";
      currentOctets = 0;
    }
    current += char;
    currentOctets += octets;
  }
  parts.push(current);
  return parts.join("\r\n ");
}

export function buildCalendar(events: readonly CalendarEvent[], now: Date = new Date()): string {
  const stamp = formatUtc(now);
  const lines = [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//toq-bar-ma//Almaty planned outages//RU",
    "CALSCALE:GREGORIAN",
    "METHOD:PUBLISH",
  ];

  for (const event of events) {
    lines.push(
      "BEGIN:VEVENT",
      `UID:${safeUid(event.uid)}`,
      `DTSTAMP:${stamp}`,
      `DTSTART:${toUtcStamp(event.date, event.timeFrom)}`,
      `DTEND:${toUtcStamp(event.date, event.timeTo)}`,
      `SUMMARY:${escapeText(event.summary)}`,
      `LOCATION:${escapeText(event.location)}`,
      `DESCRIPTION:${escapeText(event.description)}`,
      `URL:${safeUri(event.url)}`,
      "TRANSP:TRANSPARENT", // an outage doesn't make you busy
      "BEGIN:VALARM",
      "ACTION:DISPLAY",
      `DESCRIPTION:${escapeText(event.reminder)}`,
      `TRIGGER:${REMINDER_BEFORE}`,
      "END:VALARM",
      "END:VEVENT",
    );
  }

  lines.push("END:VCALENDAR");
  return lines.map(foldLine).join("\r\n") + "\r\n";
}

/** Shortens a long address for the event title, at a word boundary. */
export function shortenPlace(place: string, maxLength = 60): string {
  const flat = place.replace(/\s+/g, " ").trim();
  if (flat.length <= maxLength) return flat;
  const cut = flat.slice(0, maxLength);
  const lastSpace = cut.lastIndexOf(" ");
  return `${(lastSpace > maxLength / 2 ? cut.slice(0, lastSpace) : cut).replace(/[\s,;.:-]+$/u, "")}…`;
}

/** Saves the calendar as a file; phones offer to open it in the calendar app. */
export function downloadCalendar(fileName: string, content: string): void {
  const url = URL.createObjectURL(new Blob([content], { type: "text/calendar;charset=utf-8" }));
  const link = document.createElement("a");
  link.href = url;
  link.download = fileName;
  document.body.append(link);
  link.click();
  link.remove();
  // Give the browser a moment to start the download before the URL goes away.
  window.setTimeout(() => URL.revokeObjectURL(url), 1_000);
}
